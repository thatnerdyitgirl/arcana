const POS = ["гармон", "свобод", "лёгк", "легк", "надежд", "любов", "радост", "удовлетвор", "благополуч", "устойчив",
  "взаимопоним", "вдохнов", "ясност", "светл", "ресурс", "забот", "дружб", "уверенн", "открыт"];

const count = (text, stems) => stems.reduce((n, s) => n + (text.split(s).length - 1), 0);

export function cardText(card) {
  return [card.TRADITIONAL_MEANING?.summary, card.ARCANA_SYNTHESIS?.core_reading].filter(Boolean).join(" ").toLowerCase();
}

export function themesOf(text) {
  const t = text.toLowerCase();
  return Object.entries(THEMES).filter(([, v]) => count(t, v.stems) > 0).map(([k]) => k);
}

// −1 (тяжёлая) … +1 (лёгкая)
export function valenceOf(card) {
  const t = cardText(card);
  const neg = count(t, NEG), pos = count(t, POS);
  return (pos - neg) / (pos + neg + 1);
}

// Наклон вопроса: <0 — человек описывает трудность, >0 — ищет ресурс/развитие
export function questionLean(q = "") {
  const t = q.toLowerCase();
  const hard = count(t, ["застря", "снова", "мешает", "не могу", "боюсь", "страш", "больно", "одинок", "тревож", "не понимаю"]);
  const grow = count(t, ["развить", "поможет", "ресурс", "куда направить", "как лучше", "хочу"]);
  return Math.sign(grow - hard);
}
