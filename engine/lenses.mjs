const lnHasAny = (t, list) => list.some((s) => t.includes(s));

export function selfFigures(source) {
  const t = String(source ?? "").toLowerCase();
  return { active: lnHasAny(t, SELF_ACTIVE), passive: lnHasAny(t, SELF_PASSIVE) };
}

const SELF_A = "Эго, рацио, перфекционизм";
const SELF_P = "Внутренний Ребёнок, зажатый творческий или сексуальный ресурс";

export function selfLine(fig) {
  if (fig.active && fig.passive) return `Читая фигуры как части одной тебя: здесь спорят Внутренний Критик (${SELF_A}) и Тень (${SELF_P}). Так ты сейчас обходишься со своими желаниями и страхами.`;
  if (fig.active) return "Читая фигуру как часть тебя: здесь громче говорит Внутренний Критик, то есть Эго, рацио, перфекционизм. Вопрос — что именно он сейчас подавляет.";
  if (fig.passive) return "Читая фигуру как часть тебя: здесь проявляется Тень и Внутренний Ребёнок — зажатый творческий или сексуальный ресурс. Вопрос — насколько ему сейчас безопасно проявляться.";
  return null;
}

// ---------- применение линзы к тексту одной карты ----------

// opts: { cat: "rel"|"biz"|"self"|null, past: bool, source: полный текст карты (для определения метафор и фигур), extra: bool }
// extra=false — только замены внутри текста, без добавочных предложений (для коротких вставок)
export function applyLens(text, { cat, past = false, source = "", extra = true } = {}) {
  if (!text || !cat) return text;
  if (cat === "rel") return past ? relPast(text) : text;
  if (cat === "biz") {
    const g = bizGloss(text, 1);
    if (g.glossed || !extra) return g.text;
    const f = bizFamilyOf(source);
    return f ? `${lnEndDot(text)} Если перевести на язык дела, здесь может звучать тема: ${f.biz}.` : text;
  }
  if (cat === "self") {
    if (!extra) return text;
    const line = selfLine(selfFigures(source));
    return line ? `${lnEndDot(text)} ${line}` : text;
  }
  return text;
}

const lnEndDot = (t) => (/[.!?…]\s*$/.test(t) ? t.trim() : t.trim() + ".");

