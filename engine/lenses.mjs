// parts: [{ pos, name, say }] для 1–3 позиций; rels — отношения соседних карт
export function connectedFlow(parts, rels = []) {
  const [a, b, c] = parts;
  if (!a) return "";
  const card = (x) => `карта «${x.name}»`;
  if (!b) return `В основе («${a.pos}») лежит ${card(a)}: ${lnLower(lnTrim(a.say))}.`;
  const mid = (LINK_MID[rels[0]] ?? LINK_MID.plain)(b);
  let out = `Поскольку в твоём базисе («${a.pos}») лежит ${card(a)} (${lnLower(lnTrim(a.say))}), ${mid} (${lnLower(lnTrim(b.say))}).`;
  if (c) {
    const exit = LINK_EXIT[rels[1]] ?? LINK_EXIT.plain;
    out += ` ${exit} карте «${c.name}» («${c.pos}»): ${lnLower(lnTrim(c.say))}.`;
  }
  return out;
}
