/** Полная пересборка для «Алхимии страсти». */
function alchemy(r, { cardSource, loadCard }) {
  const sc = r.screen, cards = r.cards;
  const parts = cards.map((c, i) => {
    const el = elemKey(c), h = hOf(c), n = c.number ?? 0;
    const fig = figuresLine(c, cardSource);
    const own = (key, k) => first(layerText(c, key), k);
    const { strength, shadow } = strengthShadow(c);
    let analysis, doNow;
    if (i === 0) {
      analysis = [STATE[el].t, STATE_NUM[n] ?? "", own("self_development", 1), TONE[0], fig].filter(Boolean).join(" ");
      doNow = "Назвать своё состояние одним словом (голод, скука, нежность, злость) и заметить, в каком месте тела это ощущается.";
    } else if (i === 1) {
      const [leak] = pick(LEAK[el], h);
      analysis = [`Избыток энергии уходит в ${leak}.`, first(c.card.IN_SHADOW, 1), own("psychology", 1), TONE[1], fig].filter(Boolean).join(" ");
      doNow = "Заметить, на что за день уходит энергия, и вернуть себе 10 минут: поставить таймер и сделать что-то для себя.";
    } else {
      const [ch] = pick(CHANNEL[el], h), [ch2] = pick(CHANNEL[el], h + 1);
      analysis = [`Лучшие каналы для этой энергии: ${ch}; а ещё ${ch2}.`, own("creative", 1) || own("self_development", 1), TONE[2], fig].filter(Boolean).join(" ");
      doNow = pick(SMALL[el], h);
    }
    return { analysis: dot(analysis).replace(/\.\./g, "."), doNow, strength, shadow, el, h };
  });
  parts.forEach((p, i) => {
    const d = sc.cards[i]; d.analysis = p.analysis; d.doNow = p.doNow; d.strength = p.strength; d.shadow = p.shadow;
  });
  const names = cards.map((c) => c.name), pos = r.positions.map((p) => p.name.replace(/[.?\s]+$/, ""));
  const st = STATE[parts[0].el].label, lk = pick(LEAK[parts[1].el], parts[1].h)[1], ch = pick(CHANNEL[parts[2].el], parts[2].h)[1];
  const flow = `Сейчас импульс звучит через карту «${names[0]}», избыток утекает через карту «${names[1]}», а выходом может стать карта «${names[2]}». Это твой личный маршрут: от состояния к утечке и дальше к каналу.`;
  const insight = `Твоя энергия — ресурс, а не проблема. Состояние: ${st}. Энергия утекает в ${lk}, а самый живой канал сейчас — ${ch}.`;
  const question = "Что именно просит выхода сейчас: тело, голова или воображение, и во что я могу превратить это уже сегодня?";
  const action = "Выбери на этой неделе один канал из расклада и уделяй этому хотя бы 20 минут без оценки результата.";
  let lesson = r.synthesis.lesson;
  if (lesson?.cardId) {
    let q; try { q = loadCard(lesson.cardId); } catch { q = null; }
    lesson = { ...lesson, paragraphs: [
      `Все три карты сходятся в одной точке — ${lesson.card}.`,
      q ? (first(layerText(q, "self_development"), 1) || "Карта напоминает: энергия просит сознательного выбора, куда направиться.") : "Карта напоминает: энергия просит сознательного выбора, куда направиться.",
      "Вопрос на вывод: что в этом желании хочет стать твоим делом, твоим телом в заботе или твоим текстом?",
    ], weak: null };
  }
  apply(r, { flow, insight, question, action, lesson });
}

/** Лёгкая очистка для остальных соло-раскладов: вырезаем чужих людей, дыры закрываем текстом слоя «Саморазвитие». */
function filterOnly(r, { cardSource }) {
  const sc = r.screen;
  r.cards.forEach((c, i) => {
    const d = sc.cards[i], sd = first(layerText(c, "self_development"), 2);
    const fallbackA = sd || "Карта показывает внутреннее состояние: стоит заметить, что в тебе откликается, и не торопить себя.";
    d.analysis = [soloClean(d.analysis) || fallbackA, figuresLine(c, cardSource)].filter(Boolean).join(" ");
    d.doNow = soloClean(d.doNow) || pick(SMALL[elemKey(c)], hOf(c));
    const ss = strengthShadow(c); d.strength = soloClean(d.strength) || ss.strength; d.shadow = soloClean(d.shadow) || ss.shadow;
  });
  const names = r.cards.map((c) => c.name);
  const flow = `Три карты складываются в один внутренний маршрут: «${names[0]}», затем «${names[1]}», затем «${names[2]}». Читай их как этапы твоего собственного процесса, а не как историю с кем-то ещё.`;
  const insight = soloClean(sc.insight) || `Главный акцент расклада — карта «${names[r.synthesis.keyIdx ?? 0] ?? names[0]}»: это про твой внутренний процесс.`;
  const question = soloClean(sc.question) || r.spread.question;
  const action = soloClean(sc.action) || "Выбери одно маленькое действие из этого расклада и сделай это сегодня в своём темпе.";
  let lesson = r.synthesis.lesson;
  if (lesson) lesson = { ...lesson, paragraphs: (lesson.paragraphs ?? []).map(soloClean).filter(Boolean), weak: soloClean(lesson.weak) || null };
  apply(r, { flow, insight, question, action, lesson });
}

function apply(r, { flow, insight, question, action, lesson }) {
  const s = r.synthesis, sc = r.screen;
  s.flow = sc.flow = flow; s.insight = sc.insight = insight; s.question = sc.question = question; s.action = sc.action = action;
  s.cardQuestion = sc.cardQuestion = ""; s.lensQuestion = sc.lensQuestion = null; s.lensNote = null; s.projection = sc.projection = null; sc.synergy = ""; s.synergy = "";
  if (lesson) s.lesson = sc.lesson = lesson;
  r.lens = null;
}

// На экране ни одно предложение не повторяется: убираем повторы, а слишком короткие разборы достраиваем
const PAD = ["Заметь, что в тебе откликается на этот образ, и не торопи себя с выводами.", "Посмотри, как эта тема живёт в твоём теле: где тепло, а где напряжение.", "Спроси себя, что здесь на самом деле тебе по силам уже сегодня."];
const PAD_S = ["Живая энергия, которая просит осознанного выхода.", "Умение замечать свои желания и бережно относиться к себе.", "Ресурс, который можно направить в дело, тело или текст."];
const PAD_H = ["Внутренний ценз и стыд, из-за которых энергия уходит в самокопание.", "Привычка откладывать себя «на потом» и заглушать желание делами.", "Недоверие к собственным желаниям и попытка сразу их оценить."];
function dedupe(r) {
  const sc = r.screen, seen = [];
  const keep = (text) => sentences(text).filter((x) => { if (x.split(/\s+/).length < 5) return true; if (seen.some((y) => cmpSimilar(y, x))) return false; seen.push(x); return true; }).join(" ");
  sc.cards.forEach((c, i) => {
    const el = elemKey(r.cards[i]), h = hOf(r.cards[i]);
    c.analysis = keep(c.analysis);
    if (c.analysis.length < 60) c.analysis = (c.analysis + " " + keep(PAD[i % PAD.length])).trim();
    c.doNow = keep(c.doNow) || keep(pick(SMALL[el], h + 1)) || keep(pick(SMALL[el], h + 2)) || "Сделай один маленький шаг в своём темпе.";
    c.strength = keep(c.strength) || keep(PAD_S[i % PAD_S.length]) || c.strength;
    c.shadow = keep(c.shadow) || keep(PAD_H[i % PAD_H.length]) || c.shadow;
  });
  for (const k of ["flow", "insight", "question", "action"]) { sc[k] = keep(sc[k]) || sc[k]; r.synthesis[k] = sc[k]; }
  if (sc.lesson?.paragraphs) sc.lesson.paragraphs = sc.lesson.paragraphs.map(keep).filter(Boolean);
}

export function soloOverlay(r, deps) {
  if (!r.spread.solo || r.deck !== "MANARA") return;
  if (r.spread.solo === "alchemy") alchemy(r, deps); else filterOnly(r, deps);
  dedupe(r);
}
